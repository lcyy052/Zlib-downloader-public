import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const origin = process.env.TEST_ORIGIN || 'http://127.0.0.1:3210';
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'chrome', headless: true });
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin);
  await page.waitForFunction(() => !document.querySelector('#demo-banner').hidden);
  assert.equal(await page.locator('#exit-app').isVisible(), true);
  const initialState = await (await context.request.get(`${origin}/api/state`)).json();
  if (initialState.queue.batches?.length) {
    const deleted = await context.request.post(`${origin}/api/queue/action`, { headers: { 'X-Local-Client': '1' }, data: { action: 'batch-delete-selected', ids: initialState.queue.batches.map(batch => batch.id) } });
    assert.equal(deleted.status(), 200);
  }
  const cleared = await context.request.post(`${origin}/api/queue/action`, { headers: { 'X-Local-Client': '1' }, data: { action: 'clear' } });
  assert.equal(cleared.status(), 200);
  await page.locator('#query').fill('a');
  await page.locator('#search-submit').click();
  await page.waitForSelector('.book-card');
  assert.ok(await page.locator('.book-card').count() >= 4);
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/search-desktop.png', fullPage: true });
  await page.locator('#search-filters [name="format"]').selectOption('PDF');
  await page.locator('#query').fill('Pride');
  await page.locator('#search-submit').click();
  await page.waitForFunction(() => document.querySelector('#results-title').textContent.includes('Pride') && document.querySelectorAll('.book-card').length === 1);
  assert.equal(await page.locator('.book-card .format-tag').innerText(), 'PDF');
  await page.locator('#select-all').check();
  await page.locator('#download-selected').click();
  await page.locator('.nav[data-view="queue"]').click();
  await page.waitForSelector('#queue-list .status-completed');
  const [download] = await Promise.all([page.waitForEvent('download'), page.locator('#queue-list a').first().click()]);
  assert.match(download.suggestedFilename(), /\.demo\.txt$/);
  await page.locator('.nav[data-view="booklist"]').click();
  await page.locator('.text-import summary').click();
  await page.locator('#booklist-text').fill('红楼梦\nWalden\n红楼梦');
  await page.locator('#parse-list').click();
  await page.waitForFunction(() => document.querySelector('#match-meta').textContent.includes('已导入 2 本'));
  await page.locator('#match-list').click();
  await page.waitForFunction(() => document.querySelectorAll('#match-results select').length === 2);
  for (const select of await page.locator('#match-results select').all()) await select.selectOption('0');
  assert.equal(await page.locator('#download-matches').isEnabled(), true);
  await page.screenshot({ path: 'test-results/booklist-desktop.png', fullPage: true });
  await page.locator('#download-matches').click();
  await page.waitForFunction(() => document.querySelectorAll('#queue-list .status-completed').length >= 3);
  const beforeBooklist = await (await context.request.get(`${origin}/api/state`)).json();
  const setSerial = await context.request.post(`${origin}/api/settings`, { headers: { 'X-Local-Client': '1' }, data: { ...beforeBooklist.settings, downloadConcurrency: 1 } });
  assert.equal(setSerial.status(), 200);
  await page.locator('.nav[data-view="booklist"]').click();
  await page.locator('#website-booklist-url').fill('https://zh.z-library.sk/booklist/123/abc/test.html');
  await page.locator('#import-website-booklist').click();
  await page.waitForFunction(() => document.querySelector('#website-booklist-meta').textContent.includes('读取完成'));
  await page.locator('#download-website-all').click();
  await page.waitForSelector('#pause-website-downloads:not([hidden])');
  await page.locator('#pause-website-downloads').click();
  await page.waitForSelector('#resume-website-downloads:not([hidden])');
  const pausedState = await (await context.request.get(`${origin}/api/state`)).json();
  assert.equal(pausedState.queue.paused, false);
  assert.equal(pausedState.queue.batches.find(batch => batch.id === pausedState.websiteBooklist.id).state, 'paused');
  assert.ok(pausedState.queue.jobs.some(job => job.status === 'queued'));
  await page.locator('#resume-website-downloads').click();
  await page.waitForFunction(() => document.querySelector('#website-booklist-progress').textContent.includes('100%'));
  await page.locator('#website-booklist-url').fill('https://zh.z-library.sk/booklist/124/def/second.html');
  await page.locator('#import-website-booklist').click();
  await page.waitForFunction(() => document.querySelector('#website-booklist-title').textContent === 'second' && document.querySelector('#website-booklist-meta').textContent.includes('读取完成'));
  await page.locator('#download-website-all').click();
  await page.waitForSelector('#cancel-website-downloads:not([hidden])');
  await page.locator('#cancel-website-downloads').click();
  await page.reload();
  await page.locator('.nav[data-view="queue"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.batch-record').length === 2);
  const completedBatch = page.locator('.batch-record').filter({ hasText: 'test' });
  await completedBatch.locator('summary').click();
  await completedBatch.locator('.batch-book-row').first().waitFor();
  assert.ok(await completedBatch.locator('.status-completed').count());
  const cancelledBatch = page.locator('.batch-record').filter({ hasText: 'second' });
  await cancelledBatch.locator('summary').click();
  const failedTitle = await cancelledBatch.locator('[data-search-title]').first().getAttribute('data-search-title');
  await cancelledBatch.locator('[data-search-title]').first().click();
  await page.waitForFunction(title => document.querySelector('#results-title').textContent.includes(title), failedTitle);
  await page.locator('.nav[data-view="queue"]').click();
  await cancelledBatch.locator('[data-batch-select]').check();
  await page.locator('#delete-selected-batches').click();
  await page.waitForFunction(() => document.querySelectorAll('.batch-record').length === 1);
  await page.screenshot({ path: 'test-results/queue-desktop.png', fullPage: true });
  await page.locator('.nav[data-view="settings"]').click();
  await page.waitForSelector('#view-settings:not([hidden])');
  await page.locator('#download-concurrency').selectOption('3');
  await page.locator('#browser-mode').selectOption('visible');
  await page.locator('#settings-form button[type="submit"]').click();
  await page.waitForFunction(() => !document.querySelector('#toast').hidden && document.querySelector('#toast').textContent.includes('设置已保存'));
  const savedState = await (await context.request.get(`${origin}/api/state`)).json();
  assert.equal(savedState.settings.downloadConcurrency, 3);
  assert.equal(savedState.settings.browserMode, 'visible');
  assert.equal(savedState.queue.concurrency, 3);
  await page.screenshot({ path: 'test-results/settings-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.nav[data-view="queue"]').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile queue layout must not overflow horizontally');
  await page.screenshot({ path: 'test-results/queue-mobile.png', fullPage: true });
  await page.locator('.nav[data-view="search"]').click();
  await page.locator('#query').fill('a');
  await page.locator('#search-submit').click();
  await page.waitForSelector('.book-card');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile layout must not overflow horizontally');
  await page.screenshot({ path: 'test-results/search-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  const crossSite = await context.request.post(`${origin}/api/queue/action`, { headers: { Origin: 'https://untrusted.example', 'X-Local-Client': '1' }, data: { action: 'resume' } });
  assert.equal(crossSite.status(), 403);
  const invalidBook = await context.request.post(`${origin}/api/queue/add`, { headers: { 'X-Local-Client': '1' }, data: { books: [{ title: 'Invalid', url: 'https://untrusted.example/book/1/x' }] } });
  assert.equal(invalidBook.status(), 400);
  console.log('PASS: format filter, selection, download + file retrieval, deduplicated booklist, candidate selection, multiple booklist records, independent pause/resume/cancel, expandable details, failed-resource actions, selected batch deletion, configurable concurrency, persisted state, mobile layout, cross-site rejection, URL validation; no browser errors.');
} finally { await browser.close(); }
